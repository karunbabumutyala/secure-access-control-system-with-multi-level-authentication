#ifndef _TYPES_H_                    // Start of conditional compilation
#define _TYPES_H_                    // Define header guard


typedef unsigned char u8;            // Unsigned 8-bit data type

typedef char s8;                     // Signed 8-bit data type

typedef unsigned short int u16;      // Unsigned 16-bit data type

typedef short int s16;               // Signed 16-bit data type

typedef unsigned int u32;            // Unsigned 32-bit data type

typedef int s32;                     // Signed 32-bit data type

typedef float f32;                   // 32-bit floating point type

typedef double d64;                  // 64-bit double precision type


#endif                               // End of conditional compilation